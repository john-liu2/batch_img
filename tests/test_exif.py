def test_get_icc_profile_empty_or_too_short():
    assert Exif.get_icc_profile(b"") == UNKNOWN
    assert Exif.get_icc_profile(b"A" * 127) == UNKNOWN


def test_get_icc_profile_valid_desc_tag():
    # Construct synthetic ICC profile data
    profile_name = "sRGB v4 ICC Profile"
    encoded_name = profile_name.encode("utf-8") + b"\x00"
    str_len = len(encoded_name)

    # 128 bytes header + tag count (1 tag)
    data = bytearray(128)
    data.extend(struct.pack(">I", 1))

    # Tag entry: 'desc', tag_offset = 144, tag_size = 12 + len
    tag_offset = 144
    tag_size = 12 + str_len
    data.extend(b"desc")
    data.extend(struct.pack(">I", tag_offset))
    data.extend(struct.pack(">I", tag_size))

    # Data block for 'desc' tag
    data_block = (
        b"desc" + b"\x00\x00\x00\x00" + struct.pack(">I", str_len) + encoded_name
    )
    data.extend(data_block)

    assert Exif.get_icc_profile(bytes(data)) == profile_name


def test_get_icc_profile_fallback_search():
    # 128 header + 0 tag count, followed by embedded string in the first 1000 bytes
    data = bytearray(128)
    data.extend(struct.pack(">I", 0))
    data.extend(b"\x00" * 200)
    data.extend(b"Display P3")
    data.extend(b"\x00" * 200)

    assert Exif.get_icc_profile(bytes(data)) == "Display P3"


def test_get_icc_profile_unknown_fallback():
    # 128 header + 0 tags, no matching keywords
    data = bytearray(128)
    data.extend(struct.pack(">I", 0))
    data.extend(b"\x00" * 200)

    assert Exif.get_icc_profile(bytes(data)) == UNKNOWN


def test_get_icc_profile_corrupted_structure_handled():
    # Header long enough, but claims 1 tag while buffer ends abruptly
    data = bytearray(128)
    data.extend(struct.pack(">I", 1))
    data.extend(b"desc")  # Truncated tag record

    assert Exif.get_icc_profile(bytes(data)) == "Error getting ICC profile name"


